local H = require("./Harness")
local Mock = require("./MockRoblox")
local M = require("../src/UI/Editor/EditorModel")
local C = require("../src/Engine/Console")
local E = require("../src/Engine/Execution")
local Config = require("../src/Core/Config")
local UI = require("../src/UI/UIManager")
H.test("UI mounts in PlayerGui and actions remain reachable after Hide", function()
    local playerGui, _, host = Mock.installUI()
    Config.init(nil)
    local model, console = M.new(), C.new()
    local ui = UI.new(model, console, E.new(console, nil), Config, host)
    H.eq(ui.gui.Parent, playerGui)
    local root = ui.gui:FindFirstChild("Window")
    local bar = root:FindFirstChild("Toolbar")
    local function click(name)
        local b = bar:FindFirstChild(name)
        H.ok(b)
        b.MouseButton1Click:Fire()
    end
    ui.view.box.Text = "needle and needle"
    H.eq(model:current().doc:text(), "needle and needle")
    click("Undo") H.eq(model:current().doc:text(), "-- Write Luau here\nprint(\"Hello, world!\")")
    click("Redo") H.eq(model:current().doc:text(), "needle and needle")
    root:FindFirstChild("FindQuery").Text = "needle"
    click("Find")
    H.ok(console:text():find("2 matches", 1, true))
    click("New tab") H.eq(#model.tabs, 2)
    click("Close tab") H.eq(#model.tabs, 1)
    click("Run") H.ok(console:text():find("unavailable", 1, true))
    click("Hide") H.eq(root.Visible, false)
    ui.gui:FindFirstChild("Silver").MouseButton1Click:Fire()
    H.eq(root.Visible, true)
    ui.gui:Destroy()
end)
return true
