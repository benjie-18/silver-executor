local H = require("./Harness")
local S = require("../src/UI/Editor/Search")
local D = require("../src/UI/Editor/Document")
H.test("whole word and case", function()
    local m = S.findAll({"cat scatter Cat"}, "cat", {word = true})
    H.eq(#m, 2)
    H.eq(#S.findAll({"Cat cat"}, "cat", {caseSensitive = true}), 1)
end)
H.test("replace all uses single undo and handles invalid pattern", function()
    local d = D.new("aba aba")
    local n = S.replaceAll(d, "aba", "X")
    H.eq(n, 2) H.eq(d:text(), "X X") H.eq(#d.undoStack, 1)
    H.ok(d:undo()) H.eq(d:text(), "aba aba")
    local m, err = S.findAll(d.lines, "[", {pattern = true})
    H.eq(#m, 0) H.ok(err)
end)
return true
