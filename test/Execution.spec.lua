local H = require("./Harness")
local C = require("../src/Engine/Console")
local E = require("../src/Engine/Execution")
local Mock = require("./MockRoblox")
H.test("unavailable compiler fails closed", function()
    local e = E.new(C.new(), nil)
    local ok = e:run("return 1") H.eq(ok, false) H.eq(e.state, "idle")
end)
H.test("compile runtime and successful runs", function()
    local c = C.new() local e = E.new(c, Mock.compiler)
    H.eq(e:run("this is not luau"), false) H.eq(e.state, "error")
    H.ok(e:run('error("boom")')) H.eq(e.state, "error")
    H.ok(e:run("local x = 2 + 2")) H.eq(e.state, "finished")
end)
H.test("stop invalidates queued work", function()
    local schedule, flush = Mock.scheduler()
    local c = C.new() local e = E.new(c, Mock.compiler, schedule)
    H.ok(e:run('error("should not execute")')) H.ok(e:stop())
    flush() H.eq(e.state, "stopped")
end)
H.test("scheduler errors do not leave runner stuck", function()
    local c = C.new()
    local e = E.new(c, Mock.compiler, function() error("no scheduler") end)
    H.eq(e:run("return true"), false)
    H.eq(e.state, "error")
end)
return true
